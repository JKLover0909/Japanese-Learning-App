#!/usr/bin/env bash
# PreToolUse guard for file tools. Keeps secrets and learner data out of the conversation and
# protects files that may only change through their own workflow.
set -euo pipefail

ROOT=${CLAUDE_PROJECT_DIR:-$PWD}
input=$(cat)
tool=$(jq -r '.tool_name // empty' <<<"$input")
path=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // .tool_input.path // empty' <<<"$input")
[[ -n "$path" ]] || exit 0
[[ "$path" == /* ]] || path="$ROOT/$path"
rel=${path#"$ROOT"/}
name=${path##*/}

decide() {
  jq -n --arg decision "$1" --arg reason "$2" \
    '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $decision, permissionDecisionReason: $reason}}'
  exit 0
}

case "$name" in
  .env.example) ;;
  .env | .env.*) decide deny 'Do not read or write .env files (secrets). Use .env.example for documented settings.' ;;
  *.db | *.db-wal | *.db-shm | *.db-journal | *.sqlite3) decide deny 'Database files may hold real learner data. Ask the user.' ;;
esac
case "$rel" in
  data | data/* | backend/data | backend/data/*) decide deny 'data/ holds the local database and backups, which may contain real learner data.' ;;
esac
[[ "$tool" == Read || "$tool" == Grep ]] && exit 0

case "$rel" in
  backend/alembic/versions/*.py)
    if git -C "$ROOT" ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
      decide deny 'Committed migrations must not be edited. Add a new revision: cd backend && .venv/bin/alembic revision --autogenerate -m "..."'
    fi
    ;;
  backend/app/content/audio.json | frontend/public/assets/audio/*)
    decide ask 'Audio clips and audio.json are generated by backend/scripts/generate_audio.py (see docs/development.md#listening-test-audio).'
    ;;
esac
exit 0
